# Node 20+ already here, or the one under the prefix; empty when neither.
NODE=""
find_node() {
  local cand v
  for cand in "$NODE_HOME/bin/node" "$(command -v node 2>/dev/null || true)"; do
    [ -n "$cand" ] && [ -x "$cand" ] || continue
    v=$("$cand" -p 'process.versions.node' 2>/dev/null) || continue
    if [ "${v%%.*}" -ge "$NODE_MIN_MAJOR" ] 2>/dev/null; then NODE="$cand"; NODE_FOUND="$v"; return 0; fi
  done
  return 1
}

install_node() {
  local arch tarball url sums dir
  case "$(uname -m)" in x86_64|amd64) arch=x64 ;; aarch64|arm64) arch=arm64 ;; *) die "No Node.js build for $(uname -m): install Node $NODE_MIN_MAJOR or later yourself, then run this again." ;; esac
  tarball="node-v$NODE_VERSION-linux-$arch.tar.xz"
  url="https://nodejs.org/dist/v$NODE_VERSION"
  if [ "$DRY" = 1 ]; then say "   would download $url/$tarball, check it against SHASUMS256.txt and unpack it into $NODE_HOME"; NODE="$NODE_HOME/bin/node"; return 0; fi
  dir=$(mktemp -d) || return 1
  fetch "$url/$tarball" "$dir/$tarball" && fetch "$url/SHASUMS256.txt" "$dir/SHASUMS256.txt" || { rm -rf "$dir"; die "Couldn't download Node.js from nodejs.org."; }
  ( cd "$dir" && grep " $tarball\$" SHASUMS256.txt | sha256sum -c --status ) || { rm -rf "$dir"; die "The Node.js download doesn't match nodejs.org's checksum: not installed."; }
  rm -rf "$NODE_HOME" && mkdir -p "$NODE_HOME" && tar -xJf "$dir/$tarball" -C "$NODE_HOME" --strip-components=1 --no-same-owner || { rm -rf "$dir"; die "Couldn't unpack Node.js."; }
  rm -rf "$dir"
  NODE="$NODE_HOME/bin/node"
}

# The release: its manifest (signed with the pinned key) and the bundle it names.
# Sets REL_VERSION and REL_BUNDLE (a verified file).
# The bundle into a folder of its own. --no-same-owner: a bundle built on Windows names owners
# that root in an unprivileged container can't assign (everything is chowned later anyway).
# umask 022 + --no-same-permissions: such a bundle also records every file and folder as
# writable by anyone (bsdtar has no modes to read there), and root would keep that.
unpack() {
  (umask 022 && mkdir -p "$1" && tar -xzf "$REL_BUNDLE" -C "$1" --no-same-owner --no-same-permissions)
}

get_release() {
  local dir mf bundle
  dir=$(mktemp -d) || return 1
  WORK="$dir"
  if [ -n "$BUNDLE" ]; then
    [ -n "$MANIFEST" ] || die "--bundle needs --manifest (the release's update-manifest.json), to check its signature."
    mf="$MANIFEST"; bundle="$BUNDLE"
  else
    local base="$RELEASES/latest/download"
    [ -n "$WANT_VERSION" ] && base="$RELEASES/download/v$WANT_VERSION"
    mf="$dir/update-manifest.json"
    if [ "$DRY" = 1 ]; then say "   would download $base/update-manifest.json and the bundle it names, and check its signature"; REL_VERSION="${WANT_VERSION:-latest}"; return 0; fi
    fetch "$base/update-manifest.json" "$mf" || die "Couldn't download the release manifest from $base."
  fi
  local out
  out=$("$NODE" -e '
    const c = require("crypto"), fs = require("fs");
    const m = JSON.parse(fs.readFileSync(process.argv[1], "utf8"));
    const pem = "-----BEGIN PUBLIC KEY-----\n" + process.argv[2] + "\n-----END PUBLIC KEY-----\n";
    const payload = Buffer.from(`${m.version}\n${m.size || 0}\n${String(m.sha256).toLowerCase()}`);
    const good = m.signature && c.verify(null, payload, c.createPublicKey(pem), Buffer.from(String(m.signature), "base64"));
    if (!good || !/^[0-9a-f]{64}$/i.test(String(m.sha256)) || !/^\d+\.\d+\.\d+$/.test(String(m.version))) { console.log("BAD"); process.exit(0); }
    console.log([m.version, String(m.sha256).toLowerCase(), m.size || 0, m.url || ""].join(" "));
  ' "$mf" "$PUBKEY" 2>/dev/null) || out="BAD"
  [ "$out" = "BAD" ] && die "The release manifest isn't signed with OpsPoint's release key: nothing was installed."
  local ver sha size url
  read -r ver sha size url <<<"$out"
  if [ -z "$BUNDLE" ]; then
    bundle="$dir/opspoint-$ver.tar.gz"
    case "$url" in "$RELEASES"/*) ;; *) die "The manifest names a download outside OpsPoint's releases: $url" ;; esac
    fetch "$url" "$bundle" || die "Couldn't download $url."
  fi
  local got; got=$(sha256sum "$bundle" | cut -d' ' -f1)
  [ "$got" = "$sha" ] || die "The bundle doesn't match its signed manifest (sha256): nothing was installed."
  [ "$(stat -c %s "$bundle")" = "$size" ] || die "The bundle's size doesn't match its signed manifest: nothing was installed."
  REL_VERSION="$ver"; REL_BUNDLE="$bundle"
}

# Run the OpsPoint command line as the service account, with its settings.
cli() {
  local cmd=("$NODE" "$APP/server/cli/opspoint.js" "$@")
  if [ "$(id -u)" = 0 ]; then (cd "$APP" && runuser -u "$SERVICE_USER" -- env OPSPOINT_CONFIG="$CONFIG" "${cmd[@]}")
  elif [ "$(id -un)" = "$SERVICE_USER" ]; then (cd "$APP" && OPSPOINT_CONFIG="$CONFIG" "${cmd[@]}")
  else die "Run this with sudo (the command line runs as the $SERVICE_USER account)."; fi
}

machine_zone() {
  local z=""
  z=$(timedatectl show -p Timezone --value 2>/dev/null || true)
  [ -z "$z" ] && [ -f /etc/timezone ] && z=$(cat /etc/timezone)
  [ -z "$z" ] && [ -L /etc/localtime ] && z=$(readlink /etc/localtime | sed 's|.*/zoneinfo/||')
  printf '%s' "${z:-UTC}"
}
