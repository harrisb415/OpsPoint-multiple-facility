# OpsPoint for Linux: the installer, and afterwards the maintenance tool
# (installed as /usr/local/bin/opspoint).
#
#   sudo bash install.sh                              menus (arrow keys or number keys)
#   sudo bash install.sh --config answers.env --yes   unattended, no menus (automation, CI)
#   sudo opspoint                                     after installing: the same menus
#   opspoint doctor | export | import FILE | drill DIR | backups | settings | migrate | setup-code
#                                                     the command line, as the service account
#
# Options
#   --config FILE      answers, KEY=value lines (below); a question is asked for each
#                      one not given, unless --yes takes its default
#   --yes              no questions: the answers file and the defaults
#   --no-color         plain text (also NO_COLOR=1, and whenever the output isn't a terminal)
#   --version X.Y.Z    a release other than the newest
#   --bundle FILE --manifest FILE   install from files already here (no download)
#   --prefix DIR       where OpsPoint lives (default /opt/opspoint)
#   --dry-run          say what would happen; change nothing (no root needed)
#   --help
#
# Answers
#   TZ=America/Chicago            the facility's time zone (asked when this machine is on UTC)
#   PORT=3000                     OPSPOINT_DATA=/var/lib/opspoint
#   OPSPOINT_DB_DRIVER=sqlite     or pg, with DATABASE_URL=postgresql://user:pass@host:5432/db
#   PGSSLMODE=verify-full         TLS to Postgres: verify-full, verify-ca, require or disable
#                                 (default disable for a database on this machine)
#   SERVICE=systemd               or pm2 (when the machine has no systemd)
#   ADDRESS=ops.example.org       the name or address the setup link uses (default: this
