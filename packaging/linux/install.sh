# A progress bar redrawn in place (one line per step when not a terminal).
BAR_W=20
progress() {  # progress PERCENT WORDS
  local pct=$1; shift
  local fill=$(( pct * BAR_W / 100 )) bar=""
  bar="$(printf '█%.0s' $(seq 1 $((fill > 0 ? fill : 1))))"; [ "$fill" = 0 ] && bar=""
  bar="$bar$(printf '░%.0s' $(seq 1 $((BAR_W - fill > 0 ? BAR_W - fill : 1))))"; [ "$fill" -ge "$BAR_W" ] && bar="$(printf '█%.0s' $(seq 1 "$BAR_W"))"
  if [ "$TTY" = 1 ]; then printf '\r\033[K   %s %s%s%s %3d%%  %s' "$W_INSTALLING" "$GOLD" "$bar" "$OFF" "$pct" "$*"
  else printf '   %s %3d%%  %s\n' "$W_INSTALLING" "$pct" "$*"; fi
}
progress_end() { [ "$TTY" = 1 ] && printf '\n'; return 0; }

# ── Asking things ───────────────────────────────────────────────────────────
# menu TITLE QUESTION "key|id|label"... -> prints the chosen id
# MENU_DEFAULT (an id) is where the highlight starts: Enter alone must never
# start something heavy (on an installed machine, the health check).
MENU_DEFAULT=""
menu() {
  local title=$1 question=$2; shift 2
  local items=("$@") i key id label start=0 n=$#
  for ((i = 0; i < n; i++)); do IFS='|' read -r key id label <<<"${items[$i]}"; [ "$id" = "$MENU_DEFAULT" ] && start=$i; done
  if [ "$WHIP" = 1 ]; then
    local args=() def
    for i in "${items[@]}"; do IFS='|' read -r key id label <<<"$i"; args+=("$key" "$label"); done
    IFS='|' read -r def id label <<<"${items[$start]}"
    local pick
    pick=$(whiptail --title " $title " --default-item "$def" --menu "\n$question" 18 64 "${#items[@]}" "${args[@]}" 3>&1 1>&2 2>&3) || { echo quit; return 0; }
    for i in "${items[@]}"; do IFS='|' read -r key id label <<<"$i"; [ "$key" = "$pick" ] && { echo "$id"; return 0; }; done
    echo quit; return 0
  fi
  if [ "$TTY" = 1 ] && [ "$DEPTH" != 0 ]; then
    # Arrow keys and number keys, redrawn in place.
    local sel=$start k rest
    printf '   %s\n\n' "$question" >&2
    while :; do
      for ((i = 0; i < n; i++)); do
        IFS='|' read -r key id label <<<"${items[$i]}"
        if [ "$i" = "$sel" ]; then printf '\033[K   %s▸ %s%s\n' "$GOLD$BOLD" "$label" "$OFF" >&2
        else printf '\033[K     %s%s%s\n' "$SILVER" "$label" "$OFF" >&2; fi
      done
      printf '\n\033[K   %s%s%s' "$DIM" "$MENU_HINTS" "$OFF" >&2
      IFS= read -rsn1 k </dev/tty || k=q
      if [ "$k" = $'\033' ]; then IFS= read -rsn2 -t 0.1 rest </dev/tty || rest=""; k="$k$rest"; fi
      case "$k" in
        $'\033[A') sel=$(( (sel + n - 1) % n )) ;;
        $'\033[B') sel=$(( (sel + 1) % n )) ;;
        '') IFS='|' read -r key id label <<<"${items[$sel]}"; printf '\n\n' >&2; echo "$id"; return 0 ;;
        *) for i in "${items[@]}"; do IFS='|' read -r key id label <<<"$i"
             if [ "$key" = "${k,,}" ]; then printf '\n\n' >&2; echo "$id"; return 0; fi; done ;;
      esac
      printf '\r\033[%dA' "$((n + 1))" >&2
    done
  fi
  # Plain numbered prompt.
  printf '   %s\n' "$question" >&2
  for i in "${items[@]}"; do IFS='|' read -r key id label <<<"$i"; printf '     %s) %s\n' "$key" "$label" >&2; done
  local answer
  while :; do
    printf '   Choose: ' >&2
    IFS= read -r answer || { echo quit; return 0; }
    for i in "${items[@]}"; do IFS='|' read -r key id label <<<"$i"; [ "$key" = "${answer,,}" ] && { echo "$id"; return 0; }; done
  done
}

# ask NAME QUESTION DEFAULT -> sets $NAME (answers file first; --yes takes the default)
ask() {
  local name=$1 question=$2 def=$3 val
  if [ -n "${!name:-}" ]; then return 0; fi
  if [ "$YES" = 1 ] || [ "$TTY" = 0 ]; then printf -v "$name" '%s' "$def"; return 0; fi
  if [ "$WHIP" = 1 ]; then
    val=$(whiptail --title " $BRAND_TITLE " --inputbox "\n$question" 11 70 "$def" 3>&1 1>&2 2>&3) || exit 1
  else
    printf '   %s %s[%s]%s ' "$question" "$DIM" "$def" "$OFF"
    IFS= read -r val || val=""
    [ -z "$val" ] && val="$def"
  fi
  printf -v "$name" '%s' "$val"
}
# yesno QUESTION DEFAULT(y|n) -> 0 for yes
yesno() {
  local q=$1 def=${2:-y} a
  if [ "$YES" = 1 ] || [ "$TTY" = 0 ]; then [ "$def" = y ]; return; fi
  if [ "$WHIP" = 1 ]; then
    if [ "$def" = y ]; then whiptail --title " $BRAND_TITLE " --yesno "\n$q" 10 70; else whiptail --title " $BRAND_TITLE " --defaultno --yesno "\n$q" 10 70; fi
    return
  fi
  printf '   %s %s ' "$q" "$([ "$def" = y ] && echo '[Y/n]' || echo '[y/N]')"
  IFS= read -r a || a=""
  a=${a:-$def}; [[ "${a,,}" == y* ]]
}

# ── Doing things (or, with --dry-run, saying so) ───────────────────────────
run() { if [ "$DRY" = 1 ]; then say "   would run: $*"; else "$@"; fi; }
runq() { if [ "$DRY" = 1 ]; then say "   would run: $*"; else "$@" >/dev/null 2>&1; fi; }   # its own output would break the progress line
write_file() {  # write_file PATH MODE OWNER CONTENT_SHOWN_IN_DRY_RUN < content
  local path=$1 mode=$2 owner=$3 shown=${4:-}
  if [ "$DRY" = 1 ]; then
    say "   would write $path ($mode, $owner)"; [ -n "$shown" ] && printf '%s\n' "$shown" | sed 's/^/     | /'
    cat >/dev/null; return 0
  fi
  local tmp; tmp=$(mktemp "${path}.XXXXXX") || return 1
  cat >"$tmp" && chmod "$mode" "$tmp" && chown "$owner" "$tmp" && mv -f "$tmp" "$path"
}

fetch() {  # fetch URL FILE
  if command -v curl >/dev/null 2>&1; then curl -fsSL --retry 3 -o "$2" "$1"
  elif command -v wget >/dev/null 2>&1; then wget -q -O "$2" "$1"
  else return 1; fi
}

