# PM2 (machines without systemd): installed beside Node when missing, run as the
# service account with its state in the data folder.
PM2=""
ensure_pm2() {
  [ "$SERVICE" = pm2 ] || return 0
  PM2=$(command -v pm2 2>/dev/null || true)
  [ -z "$PM2" ] && [ -x "$(dirname "$NODE")/pm2" ] && PM2="$(dirname "$NODE")/pm2"
  if [ -z "$PM2" ]; then
    run env PATH="$(dirname "$NODE"):$PATH" "$(dirname "$NODE")/npm" install -g pm2 --no-audit --no-fund >/dev/null 2>&1 || [ "$DRY" = 1 ] || die "Couldn't install PM2."
    PM2="$(dirname "$NODE")/pm2"
  fi
}
pm2u() { run runuser -u "$SERVICE_USER" -- env PATH="$(dirname "$NODE"):$PATH" HOME="$OPSPOINT_DATA" PM2_HOME="$OPSPOINT_DATA/.pm2" OPSPOINT_CONFIG="$CONFIG" "$PM2" "$@"; }
service_start() {
  if [ "$SERVICE" = pm2 ]; then
    ensure_pm2
    if [ "$DRY" = 0 ] && pm2u describe opspoint >/dev/null 2>&1; then pm2u restart opspoint >/dev/null; else pm2u start "$APP/bootstrap.js" --name opspoint >/dev/null; fi
    pm2u save >/dev/null 2>&1
  else runq systemctl enable --now opspoint; fi
}
service_stop()    { if [ "$SERVICE" = pm2 ]; then ensure_pm2; pm2u stop opspoint >/dev/null 2>&1; else run systemctl stop opspoint; fi; }
service_restart() { if [ "$SERVICE" = pm2 ]; then service_start; else run systemctl restart opspoint; fi; }

# The maintenance tool comes from the release (inside the signed bundle) when it can.
install_tool() {
  local src=""
  if [ -f "$APP/packaging/linux/install.sh" ]; then src="$APP/packaging/linux/install.sh"
  elif [ -f "$0" ] && head -1 "$0" 2>/dev/null | grep -q bash; then src="$0"; fi
  if [ "$DRY" = 1 ]; then say "   would install the maintenance tool as $BIN"; return 0; fi
  if [ -n "$src" ] && [ "$src" != "$PREFIX/install.sh" ]; then cp -f "$src" "$PREFIX/install.sh"; fi
  [ -f "$PREFIX/install.sh" ] || { note "The maintenance tool isn't in this release: run this installer again for it."; return 0; }
  chmod 0755 "$PREFIX/install.sh" && ln -sf "$PREFIX/install.sh" "$BIN"
}

# The encrypted SQLite driver loads from the binaries it ships (no compiler
# needed; npm runs with --ignore-scripts). Postgres installs never load it.
sqlite_loads() {
  [ "${OPSPOINT_DB_DRIVER:-sqlite}" = sqlite ] || return 0
  (cd "$APP" && "$NODE" -e "new (require('better-sqlite3-multiple-ciphers'))(':memory:').prepare('select 1').get()" >/dev/null 2>&1)
}

probe_url() {  # probe_url URL -> 0 when it answers 2xx
  if command -v curl >/dev/null 2>&1; then curl -fsSk --max-time 2 "$1" >/dev/null 2>&1
  else wget -q -T 2 --no-check-certificate -O /dev/null "$1" 2>/dev/null; fi
}
wait_healthy() {  # up to 90 s for /healthz
  [ "$DRY" = 1 ] && { say "   would wait for http://127.0.0.1:$PORT/healthz"; return 0; }
  local i scheme=http; [ -f "$OPSPOINT_DATA/cert.pem" ] && scheme=https
  for i in $(seq 1 45); do
    probe_url "$scheme://127.0.0.1:$PORT/healthz" && return 0
    sleep 2
  done
  return 1
}

# ── Settings questions (install) ────────────────────────────────────────────
load_answers() {
  [ -n "$ANSWERS" ] || return 0
  [ -r "$ANSWERS" ] || die "Can't read the answers file $ANSWERS."
  local line k v
  # Read as data, never run: KEY=value lines; quotes around the value are dropped.
  while IFS= read -r line || [ -n "$line" ]; do
    line="${line%$'\r'}"
    [[ "$line" =~ ^[[:space:]]*(#|$) ]] && continue
    [[ "$line" =~ ^[[:space:]]*([A-Z_][A-Z0-9_]*)=(.*)$ ]] || die "Not a KEY=value line in $ANSWERS: $line"
    k="${BASH_REMATCH[1]}"; v="${BASH_REMATCH[2]}"
    v="${v#\"}"; v="${v%\"}"; v="${v#\'}"; v="${v%\'}"
    case "$k" in TZ|PORT|OPSPOINT_DATA|OPSPOINT_DB_DRIVER|DATABASE_URL|PGSSLMODE|SERVICE|ADDRESS) printf -v "$k" '%s' "$v" ;;
      *) die "$ANSWERS: $k isn't an answer this installer takes (see --help)." ;; esac
  done <"$ANSWERS"
}

questions() {
  local zone; zone=$(machine_zone)
  if [ -z "${TZ:-}" ]; then
    if [ "$zone" = "UTC" ] || [ "$zone" = "Etc/UTC" ]; then
      ask TZ "This machine's clock is on UTC. The facility's time zone (for example America/Chicago):" "America/Chicago"
    else
      TZ="$zone"
    fi
  fi
  ask PORT "Port OpsPoint answers on:" "3000"
  ask OPSPOINT_DATA "Folder for the database, photos and backups:" "/var/lib/opspoint"
  if [ -z "${OPSPOINT_DB_DRIVER:-}" ]; then
    if [ "$YES" = 1 ] || [ "$TTY" = 0 ]; then OPSPOINT_DB_DRIVER=sqlite
    else
      case "$(menu "$BRAND_TITLE" "Where does the database live?" "1|sqlite|SQLite on this machine (encrypted; simplest)" "2|pg|Postgres on another server")" in
        pg) OPSPOINT_DB_DRIVER=pg ;; quit) exit 0 ;; *) OPSPOINT_DB_DRIVER=sqlite ;; esac
    fi
  fi
  if [ "$OPSPOINT_DB_DRIVER" = pg ]; then
    ask DATABASE_URL "Postgres connection string (postgresql://user:password@host:5432/database):" ""
    [[ "${DATABASE_URL:-}" =~ ^postgres(ql)?:// ]] || die "DATABASE_URL must be a postgresql:// connection string."
    # TLS to the database: verified by default; a database on this machine needs none.
    local dbhost ssl_default=verify-full
    dbhost=$(printf '%s' "$DATABASE_URL" | sed -E 's|^[a-z]+://([^@]*@)?(\[[^]]*\]\|[^/:?]*).*|\2|')
    case "$dbhost" in localhost|127.0.0.1|'[::1]') ssl_default=disable ;; esac
    ask PGSSLMODE "TLS to the database (verify-full, verify-ca, require or disable):" "$ssl_default"
    case "$PGSSLMODE" in disable|require|verify-ca|verify-full) ;; *) die "PGSSLMODE must be verify-full, verify-ca, require or disable." ;; esac
  fi
  if [ -z "${SERVICE:-}" ]; then
    if command -v systemctl >/dev/null 2>&1 && [ -d /run/systemd/system ]; then SERVICE=systemd; else SERVICE=pm2; fi
  fi
  [[ "$PORT" =~ ^[0-9]+$ ]] && [ "$PORT" -ge 1 ] && [ "$PORT" -le 65535 ] || die "PORT must be a number from 1 to 65535."
  [[ "$OPSPOINT_DATA" = /* ]] || die "OPSPOINT_DATA must be a full path (starting with /)."
  case "$OPSPOINT_DB_DRIVER" in sqlite|pg) ;; *) die "OPSPOINT_DB_DRIVER must be sqlite or pg." ;; esac
  case "$SERVICE" in systemd|pm2) ;; *) die "SERVICE must be systemd or pm2." ;; esac
  if [ "$SERVICE" = pm2 ] && [ "$PORT" -lt 1024 ]; then die "Under pm2 OpsPoint can't take port $PORT (below 1024): use 1024 or above, behind a proxy for 80/443."; fi
}

settings_json() {  # the settings file: written by Node, so every value is quoted correctly
  "${NODE:-node}" -e '
    const e = process.env, s = { OPSPOINT_PROFILE: "linux-local", TZ: e.A_TZ, PORT: Number(e.A_PORT), OPSPOINT_DATA: e.A_DATA, OPSPOINT_DB_DRIVER: e.A_DRIVER };
    if (e.A_DRIVER === "pg") { s.DATABASE_URL = e.A_URL; s.PGSSLMODE = e.A_SSL; }
    process.stdout.write(JSON.stringify(s, null, 2) + "\n");
  ' 2>/dev/null || printf '{\n  "OPSPOINT_PROFILE": "linux-local",\n  "TZ": "%s",\n  "PORT": %s,\n  "OPSPOINT_DATA": "%s",\n  "OPSPOINT_DB_DRIVER": "%s"\n}\n' "$A_TZ" "$A_PORT" "$A_DATA" "$A_DRIVER"
}

unit_text() {
  cat <<EOF
[Unit]
Description=$BRAND_PRODUCT ($BRAND_TAGLINE)
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
User=$SERVICE_USER
Group=$SERVICE_USER
WorkingDirectory=$APP
Environment=OPSPOINT_CONFIG=$CONFIG
Environment=NODE_ENV=production
ExecStart="$NODE" $APP/bootstrap.js
Restart=on-failure
RestartSec=5
# 78 = a setting is wrong: starting again won't help, the log says what to fix.
RestartPreventExitStatus=78
NoNewPrivileges=true
PrivateTmp=true
ProtectSystem=full
$([ "$PORT" -lt 1024 ] && echo "AmbientCapabilities=CAP_NET_BIND_SERVICE")

[Install]
WantedBy=multi-user.target
EOF
}

# ── Install ─────────────────────────────────────────────────────────────────
do_install() {
  local t0=$SECONDS
  head1 "$W_CHECKING"
  if [ "$DRY" = 0 ]; then
    [ "$(id -u)" = 0 ] || die "Run the installer with sudo: it creates a service account and a system service."
    [ "$(uname -s)" = Linux ] || die "This installer is for Linux. On Windows, use the OpsPoint Setup program."
  fi
  if installed && [ "$DRY" = 0 ]; then
    note "OpsPoint $(installed_version) is already installed in $PREFIX."
    yesno "Upgrade or repair it instead?" n && { do_upgrade; return; }
    exit 0
  fi
  load_answers
  local os; os=$( (. /etc/os-release 2>/dev/null && echo "${PRETTY_NAME:-$ID}") || uname -sr)
  ok "$os, $(uname -m)"
  if find_node; then ok "Node $NODE_FOUND found ($NODE)"; else note "No Node.js $NODE_MIN_MAJOR or later: Node $NODE_VERSION will be installed in $NODE_HOME"; fi
  command -v curl >/dev/null 2>&1 || command -v wget >/dev/null 2>&1 || [ -n "$BUNDLE" ] || die "Neither curl nor wget is installed: install one, then run this again."
  command -v tar >/dev/null 2>&1 || die "tar is not installed."
  questions
  if port_free "$PORT"; then ok "Port $PORT is free"; else bad "Port $PORT is in use"; [ "$DRY" = 1 ] || die "Something else answers on port $PORT: choose another (PORT=...)."; fi
  local parent="$OPSPOINT_DATA"; while [ ! -d "$parent" ] && [ "$parent" != / ]; do parent=$(dirname "$parent"); done
  local free_gb; free_gb=$(df -Pk "$parent" 2>/dev/null | awk 'NR==2 {printf "%d", $4/1048576}')
  if [ "${free_gb:-0}" -ge 2 ]; then ok "${free_gb} GB free disk space"; else bad "Only ${free_gb:-0} GB free on $parent"; [ "$DRY" = 1 ] || die "OpsPoint needs at least 2 GB free for its data and backups."; fi
  ok "Time zone $TZ"
  ok "Database: $([ "$OPSPOINT_DB_DRIVER" = pg ] && echo "Postgres at $(printf '%s' "$DATABASE_URL" | sed -E 's|^[a-z]+://([^@]*@)?([^/?]*).*|\2|')" || echo "SQLite in $OPSPOINT_DATA")"
  ok "Runs as the $SERVICE_USER account, under $SERVICE"
  echo

  progress 5 "Getting Node.js…"
  if [ -z "$NODE" ]; then progress_end; install_node; fi
  progress 20 "Downloading OpsPoint…"
  get_release; [ "$DRY" = 1 ] && progress_end
  progress 40 "Unpacking$([ "$REL_VERSION" = latest ] || echo " v$REL_VERSION")…"
  if [ "$DRY" = 1 ]; then say "   would unpack the bundle into $APP"
  else
    id "$SERVICE_USER" >/dev/null 2>&1 || useradd --system --home-dir "$OPSPOINT_DATA" --shell /usr/sbin/nologin "$SERVICE_USER" || die "Couldn't create the $SERVICE_USER account."
    mkdir -p "$OPSPOINT_DATA" "$ETC" && unpack "$APP" || die "Couldn't unpack the bundle."
  fi
  progress 55 "Installing packages…"
  if [ "$DRY" = 1 ]; then say "   would run: npm ci --omit=dev --ignore-scripts (in $APP)"
  else
    local npm="$(dirname "$NODE")/npm"; [ -x "$npm" ] || npm=$(command -v npm)
    (cd "$APP" && PATH="$(dirname "$NODE"):$PATH" "$npm" ci --omit=dev --ignore-scripts --no-audit --no-fund >"$WORK/npm.log" 2>&1) || { progress_end; tail -20 "$WORK/npm.log" >&2; die "npm ci failed (above)."; }
    sqlite_loads || { progress_end; die "The SQLite driver has no build for this machine ($(uname -m)): use Postgres (OPSPOINT_DB_DRIVER=pg), or see docs/SUPPORT.md."; }
  fi
  progress 75 "Writing the settings…"
  A_TZ="$TZ" A_PORT="$PORT" A_DATA="$OPSPOINT_DATA" A_DRIVER="$OPSPOINT_DB_DRIVER" A_URL="${DATABASE_URL:-}" A_SSL="${PGSSLMODE:-verify-full}" export A_TZ A_PORT A_DATA A_DRIVER A_URL A_SSL
  local shown; shown=$(settings_json | sed -E 's|("DATABASE_URL": "[a-z]+://[^:/@]*:)[^@]*@|\1•••@|')
  settings_json | write_file "$CONFIG" 0640 "root:$SERVICE_USER" "$shown" || die "Couldn't write $CONFIG."
  run chown -R "$SERVICE_USER:$SERVICE_USER" "$APP" "$OPSPOINT_DATA"
  run chmod 0750 "$OPSPOINT_DATA"
  progress 85 "Registering the service…"
  if [ "$SERVICE" = systemd ]; then
    unit_text | write_file "$UNIT" 0644 root:root "$(unit_text)" || die "Couldn't write $UNIT."
    run systemctl daemon-reload
  fi
  install_tool
  progress 90 "Starting OpsPoint…"
  service_start
  wait_healthy || { progress_end; die "OpsPoint didn't start. See: journalctl -u opspoint -n 50"; }
  progress 100 "Started."
  progress_end
  finish_card "$t0"
}

finish_card() {
  local t0=${1:-$SECONDS} addr scheme=http code="" link
  echo; head1 "Health check"
  if [ "$DRY" = 1 ]; then say "   would run: opspoint doctor"
  else cli doctor | sed -n '3,$p' | sed '/^$/d; s/^/ /'; fi
  addr="${ADDRESS:-$(first_address)}"; addr="${addr:-$(hostname)}"
  [ -f "$OPSPOINT_DATA/cert.pem" ] && scheme=https
  link="$scheme://$addr:$PORT/setup"
  if { [ "$scheme" = http ] && [ "$PORT" = 80 ]; } || { [ "$scheme" = https ] && [ "$PORT" = 443 ]; }; then link="$scheme://$addr/setup"; fi
  if [ "$DRY" = 0 ]; then code=$(cli setup-code 2>/dev/null | sed -n 's/^Setup code: \([A-Z0-9-]*\).*/\1/p'); fi
  echo
  printf '   %s%s%s  (%ds)\n\n' "$GOLD$BOLD" "$W_DONE" "$OFF" "$((SECONDS - t0))"
  printf '   %s:\n   %s%s%s\n' "$W_OPEN_SETUP" "$WARM$BOLD" "$link" "$OFF"
  if [ -n "$code" ]; then printf '   %s: %s%s%s (%s)\n' "$W_SETUP_CODE" "$WARM$BOLD" "$code" "$OFF" "$W_CODE_NOTE"
  elif [ "$DRY" = 0 ]; then printf '   %s\n' "Setup is already finished here: sign in as usual."; fi
  if command -v qrencode >/dev/null 2>&1 && [ "$TTY" = 1 ] && [ "$DRY" = 0 ]; then echo; qrencode -t ANSIUTF8 -m 2 "$link" | sed 's/^/   /'; printf '   %s\n' "$W_PHONE_NOTE"; fi
  printf '\n   %sLater: sudo opspoint  (upgrade, health check, backup, export)%s\n\n' "$DIM" "$OFF"
}

# ── Upgrade or repair ───────────────────────────────────────────────────────
read_config() {  # SERVICE / PORT / OPSPOINT_DATA from what is installed
  [ -f "$CONFIG" ] || return 0
  PORT=$(sed -n 's/^ *"PORT": *\([0-9]*\).*/\1/p' "$CONFIG" | head -1); PORT=${PORT:-3000}
  OPSPOINT_DATA=$(sed -n 's/^ *"OPSPOINT_DATA": *"\([^"]*\)".*/\1/p' "$CONFIG" | head -1); OPSPOINT_DATA=${OPSPOINT_DATA:-/var/lib/opspoint}
  OPSPOINT_DB_DRIVER=$(sed -n 's/^ *"OPSPOINT_DB_DRIVER": *"\([^"]*\)".*/\1/p' "$CONFIG" | head -1); OPSPOINT_DB_DRIVER=${OPSPOINT_DB_DRIVER:-sqlite}
  if [ -f "$UNIT" ]; then SERVICE=systemd; else SERVICE=pm2; fi
}

do_upgrade() {
  installed || die "OpsPoint isn't installed in $PREFIX."
  [ "$DRY" = 1 ] || [ "$(id -u)" = 0 ] || die "Run this with sudo."
  read_config; find_node || die "Node.js $NODE_MIN_MAJOR or later is missing: run the installer again."
  local from; from=$(installed_version)
  head1 "Upgrade or repair (installed: v$from)"
  get_release
  if [ "$REL_VERSION" = "$from" ]; then yesno "v$from is the newest. Repair it (put its files back as released)?" y || return 0
  else yesno "Upgrade v$from to v$REL_VERSION?" y || return 0; fi
  progress 10 "Stopping OpsPoint…"; service_stop
  progress 25 "Keeping v$from beside it…"
  run rm -rf "$PREFIX/app.previous"; run mv "$APP" "$PREFIX/app.previous"
  progress 40 "Unpacking v$REL_VERSION…"
  # Into an empty folder: nothing of v$from stays behind among the new version's files.
  if [ "$DRY" = 0 ]; then unpack "$APP" || { progress_end; rollback "$from" "v$REL_VERSION didn't unpack"; }; fi
  progress 60 "Installing packages…"
  if [ "$DRY" = 0 ]; then
    local npm="$(dirname "$NODE")/npm"; [ -x "$npm" ] || npm=$(command -v npm)
    (cd "$APP" && PATH="$(dirname "$NODE"):$PATH" "$npm" ci --omit=dev --ignore-scripts --no-audit --no-fund >"$WORK/npm.log" 2>&1) || { progress_end; tail -20 "$WORK/npm.log" >&2; rollback "$from" "v$REL_VERSION's packages didn't install"; }
    sqlite_loads || { progress_end; rollback "$from"; }
    chown -R "$SERVICE_USER:$SERVICE_USER" "$APP"
  fi
  install_tool
  progress 85 "Starting v$REL_VERSION…"; service_restart
  if wait_healthy; then progress 100 "Running v$REL_VERSION."; progress_end; ok "Upgraded to v$REL_VERSION"
  else progress_end; rollback "$from"; fi
}

rollback() {
  local why=${2:-"v$REL_VERSION didn't start"}
  bad "$why: putting v$1 back"
  service_stop
  run rm -rf "$APP"; run mv "$PREFIX/app.previous" "$APP"
  service_restart
  wait_healthy && die "$why; v$1 is running again. See: journalctl -u opspoint -n 80" \
    || die "Neither version started. See: journalctl -u opspoint -n 80"
}

# ── Uninstall ───────────────────────────────────────────────────────────────
do_uninstall() {
  installed || die "OpsPoint isn't installed in $PREFIX."
  [ "$DRY" = 1 ] || [ "$(id -u)" = 0 ] || die "Run this with sudo."
  read_config
  head1 "Uninstall"
  # Asked, defaulting to no; `uninstall --yes` names the action, so it goes ahead (the data still stays).
  if [ "$YES" = 0 ]; then yesno "Remove OpsPoint from this machine? The data in $OPSPOINT_DATA stays unless you choose otherwise next." n || return 0; fi
  service_stop
  if [ "$SERVICE" = systemd ]; then run systemctl disable opspoint >/dev/null 2>&1; run rm -f "$UNIT"; run systemctl daemon-reload
  else pm2u delete opspoint >/dev/null 2>&1; pm2u save >/dev/null 2>&1; fi
  run rm -rf "$APP" "$PREFIX/app.previous" "$NODE_HOME" "$PREFIX/install.sh"; run rm -f "$BIN"
  [ "$DRY" = 1 ] || rmdir "$PREFIX" 2>/dev/null || true
  if yesno "Also delete the settings file ($CONFIG)? It holds this install's settings and any database password." y; then run rm -rf "$ETC"; fi
  local typed=""
  if [ "$YES" = 0 ] && [ "$TTY" = 1 ]; then
    printf '   %sTo delete every record, photo and backup in %s too, type DELETE (anything else keeps them):%s ' "$FAIL" "$OPSPOINT_DATA" "$OFF"
    IFS= read -r typed || typed=""
  fi
  if [ "$typed" = "DELETE" ]; then run rm -rf "$OPSPOINT_DATA"; run userdel "$SERVICE_USER"; ok "Removed OpsPoint and its data."
  else ok "Removed OpsPoint. The data is still in $OPSPOINT_DATA."; fi
}

# ── Backup, export, import ──────────────────────────────────────────────────
do_backup() {
  installed || die "OpsPoint isn't installed in $PREFIX."
  read_config; find_node || die "Node.js is missing: run the installer again."
  case "$(menu "Back up or restore" "Back up or restore" "1|export|Export now (one encrypted file with everything)" "2|drill|Restore drill: the newest export into a scratch install" "3|list|Show the database backups" "b|back|Back")" in
    export) cli export --out "$OPSPOINT_DATA/exports" ;;
    drill) cli drill "$OPSPOINT_DATA/exports" ;;
    # The command line knows where they go: a folder chosen in setup (backup_dir) or beside the database.
    list) cli backups ;;
  esac
}
do_export() {
  installed || die "OpsPoint isn't installed in $PREFIX."
  read_config; find_node || die "Node.js is missing: run the installer again."
  case "$(menu "Export or import" "Export or import" "1|export|Export to a file" "2|import|Import an export (into this new, empty install)" "b|back|Back")" in
    export) local out; out="$OPSPOINT_DATA/exports"; ask EXPORT_TO "Folder or file for the export:" "$out"; cli export --out "$EXPORT_TO" ;;
    import)
      ask IMPORT_FILE "The export file to import:" ""
      [ -f "$IMPORT_FILE" ] || die "There is no file at $IMPORT_FILE."
      run install -o "$SERVICE_USER" -m 0600 "$IMPORT_FILE" "$OPSPOINT_DATA/import.opspoint"
      service_stop
      cli import "$OPSPOINT_DATA/import.opspoint"; local rc=$?
      run rm -f "$OPSPOINT_DATA/import.opspoint"
      service_start
      [ "$rc" = 0 ] && finish_card ;;
  esac
}

# ── The menu ────────────────────────────────────────────────────────────────
main_menu() {
  while :; do
    banner "$(installed && installed_version)"
    if installed; then MENU_DEFAULT=doctor; else MENU_DEFAULT=install; fi
    local pick; pick=$(menu "$BRAND_TITLE" "$MENU_QUESTION" "${MENU_ITEMS[@]}")
    MENU_DEFAULT=""
    case "$pick" in
      install) do_install ;;
      upgrade) do_upgrade ;;
      doctor) installed || die "OpsPoint isn't installed in $PREFIX."; read_config; find_node; cli doctor ;;
      backup) do_backup ;;
      export) do_export ;;
      uninstall) do_uninstall; exit 0 ;;
      quit|"") exit 0 ;;
    esac
    [ "$TTY" = 1 ] || exit 0
    printf '\n   %sPress Enter for the menu%s' "$DIM" "$OFF"; IFS= read -r _ || exit 0
  done
}

WORK=""
trap '[ -n "$WORK" ] && rm -rf "$WORK"' EXIT

case "${ACTION:-}" in
  cli) installed || die "OpsPoint isn't installed in $PREFIX."; find_node || die "Node.js is missing: run the installer again."; cli "${CLI_ARGS[@]}"; exit $? ;;
  install) banner; do_install ;;
  upgrade|repair) banner "$(installed_version)"; do_upgrade ;;
  uninstall) do_uninstall ;;
  menu) main_menu ;;
  *)
    if [ "$YES" = 1 ] || [ "$TTY" = 0 ]; then banner; if installed && [ "$DRY" = 0 ]; then do_upgrade; else do_install; fi
    else main_menu; fi ;;
esac
